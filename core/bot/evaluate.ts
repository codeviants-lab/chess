const TYPES: readonly PieceSymbol[] = ['p', 'p', 'n', 'b', 'r', 'q', 'k']; // index = Board piece type

/** Static evaluation in centipawns from the point of view of the side to move. */
export function evaluate(board: Board): number {
  let white = 0;
  const sq = board.sq;
  for (let i = 0; i < 128; i++) {
    if (i & 0x88) {
      i += 7;
      continue;
    }
    const p = sq[i]!;
    if (p === 0) continue;
    const rank = i >> 4;
    const file = i & 7;
    if (p > 0) {
      const t = TYPES[p]!;
      white += PIECE_VALUE[t] + PST[t][(7 - rank) * 8 + file]!;
    } else {
      const t = TYPES[-p]!;
      white -= PIECE_VALUE[t] + PST[t][rank * 8 + file]!;
    }
  }
  return board.side === 1 ? white : -white;
}
